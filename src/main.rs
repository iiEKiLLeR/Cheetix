    fn save(&self) {
        let p = state_path();
        if let Some(d) = p.parent() {
            let _ = std::fs::create_dir_all(d);
        }
        if let Ok(s) = serde_json::to_string_pretty(&self.saved) {
            let _ = std::fs::write(p, s);
        }
    }

    fn work(&self, f: impl FnOnce(Tx) + Send + 'static) {
        let tx = self.tx.clone();
        std::thread::spawn(move || f(tx));
    }

    fn is_on(&self, cat: &str, id: &str) -> bool {
        self.saved.states.get(cat).and_then(|m| m.get(id)).copied().unwrap_or(false)
    }

    fn set_on(&mut self, cat: &str, id: &str, v: bool) {
        self.saved.states.entry(cat.into()).or_default().insert(id.into(), v);
    }

    fn go(&mut self, v: &'static str) {
        if self.view != v {
            self.view = v;
            self.view_at = Instant::now();
            self.page_filter.clear();
            self.log.clear();
        }
        match v {
            "dashboard" => self.poll_metrics(),
            "monitor" => self.refresh_procs(),
            "startup" => self.refresh_startup(),
            "powerplans" => self.refresh_plans(),
            "arena" => {
                if self.games.is_none() {
                    self.scan_games();
                }
                if self.plans.is_none() {
                    self.refresh_plans();
                }
            }
            // every visit reads the page's real state again
            _ => self.probe_page(v),
        }
    }

    /// Reads (never changes) the real state of a page's engine tweaks.
    fn probe_page(&mut self, view: &str) {
        let tweaks = self.page_tweaks(view);
        let items: Vec<Value> = tweaks.iter().filter_map(|t| t.ops.as_ref().map(|o| json!({"key": format!("{}|{}", t.c, t.id), "ops": o}))).collect();
        let scripts: Vec<(String, String)> = tweaks.iter().filter(|t| t.ops.is_none()).filter_map(|t| t.check.clone().map(|c| (format!("{}|{}", t.c, t.id), c))).collect();
        if items.is_empty() && scripts.is_empty() {
            return;
        }
        self.work(move |tx| {
            if !items.is_empty() {
                match engine::run("probe", json!({ "items": items }), 300) {
                    Ok(r) => {
                        let map = r["states"].as_object().map(|m| m.iter().map(|(k, v)| (k.clone(), v.as_str().unwrap_or("error").to_string())).collect()).unwrap_or_default();
                        tx.send(Msg::Probe(map));
                    }
                    Err(e) => {
                        tx.log(format!("{} State read failed: {e}", ts()));
                        tx.send(Msg::Probe(items.iter().filter_map(|i| i["key"].as_str()).map(|k| (k.to_string(), "error".to_string())).collect()));
                    }
                }
            }
            if !scripts.is_empty() {
                // the original check commands answer yes/no only
                let map = sys::check_batch(&scripts).into_iter().map(|(k, v)| (k, if v { "on" } else { "off" }.to_string())).collect();
                tx.send(Msg::Probe(map));
            }
        });
    }

    /// Another tweak that Cheetix applied (and holds the original for) changes one of this
    /// tweak's settings. Switching this one would overwrite or undo that tweak's work.
    fn conflict(&self, t: &Tweak) -> Option<String> {
        conflict_with(&self.tweaks, &self.saved.backups, t).map(|o| format!("\"{}\" ({} page) changes the same setting and is ON. Turn that one off first.", o.name, page_title(&o.c)))
    }

    /// Why a tweak can't be used on this PC, if it can't.
    fn unsupported(&self, t: &Tweak) -> Option<String> {
        let build: u32 = self.os.1.rsplit('.').next().and_then(|b| b.parse().ok()).unwrap_or(0);
        if let (Some([lo, hi]), true) = (t.builds, build > 0) {
            if build < lo {
                return Some(format!("Needs Windows build {lo} or newer; this PC is build {build}."));
            }
            if build > hi {
                return Some(format!("Only for Windows 10 (up to build {hi}); this PC is build {build}."));
            }
        }
        if let Some(n) = &t.needs {
            let gpu = self.os.2.to_lowercase();
            let known = !gpu.is_empty() && gpu != "--" && gpu != "n/a";
            let has = match n.as_str() {
                "nvidia" => gpu.contains("nvidia"),
                "amd" => gpu.contains("amd") || gpu.contains("radeon"),
                _ => true,
            };
            if known && !has {
                return Some(format!("Needs an {} GPU; this PC has {}.", n.to_uppercase(), self.os.2));
            }
        }
        if self.probe.get(&format!("{}|{}", t.c, t.id)).is_some_and(|s| s == "na") {
            return Some("None of the settings this tweak changes exist on this PC (service, task, logger or driver option not present).".into());
        }
        None
    }

