    /// Turn a tweak on or off by running its script on a worker thread.
    fn apply(&mut self, cat: &str, id: &str, on: bool, record: bool) {
        let key = format!("{cat}|{id}");
        if self.busy.contains(&key) {
            return;
        }
        let Some(t) = self.tweaks.iter().find(|t| t.c == cat && t.id == id).cloned() else { return };
        if let Some(ops) = t.ops.clone() {
            return self.apply_ops(&t, ops, on, record);
        }
        let Some(script) = (if on { t.on.clone() } else { t.off.clone() }) else {
            self.log.push(format!("{} {}: no script for this direction", ts(), t.name));
            return;
        };
        self.log.push(format!("{} Applying: {}", ts(), t.name));
        self.set_on(cat, id, on);
        self.status.insert(key.clone(), ("...", Instant::now()));
        self.busy.insert(key);
        let admin = self.admin;
        let (cat, id) = (cat.to_string(), id.to_string());
        self.work(move |tx| {
            let res = sys::run_bat(&script, admin).map(|out| {
                for l in out.lines().map(str::trim).filter(|l| !l.is_empty()) {
                    tx.log(l.to_string());
                }
            });
            let ok = res.is_ok();
            tx.send(Msg::TweakDone { cat, id, on, res, record });
            // Background read-back: warns in the log, never changes the switch.
            if ok && on {
                if let Some(chk) = t.check {
                    if !sys::check_one(&chk) {
                        tx.log(format!("{} {}: VERIFY WARN - the read-back check did not confirm the change", ts(), t.name));
                    }
                }
            }
        });
    }

    /// Read the real state of a page's tweaks. `items` are ("category|id", check command).
    /// Engine tweak: ON saves the original state and applies; OFF writes the saved original back.
    fn apply_ops(&mut self, t: &Tweak, ops: Vec<Value>, on: bool, record: bool) {
        let key = format!("{}|{}", t.c, t.id);
        if on {
            if let Some(why) = self.unsupported(t) {
                self.log.push(format!("{} {}: NOT SUPPORTED - {}", ts(), t.name, why));
                self.status.insert(key, ("N/A", Instant::now()));
                return;
            }
        }
        let backup = self.saved.backups.get(&key).cloned();
        // OFF with a saved original only touches this tweak's own backup, so it is always safe
        if on || backup.is_none() {
            if let Some(why) = self.conflict(t) {
                self.log.push(format!("{} {}: NOT CHANGED - {}", ts(), t.name, why));
                self.toast("Not changed", why);
                self.status.insert(key, ("BLOCKED", Instant::now()));
                return;
            }
        }
        if engine::needs_admin(&ops) && !self.admin {
            self.log.push(format!("{} {}: ERROR - {}", ts(), t.name, sys::ADMIN_MSG));
            self.status.insert(key, ("ADMIN", Instant::now()));
            return;
        }
        self.log.push(format!("{} {}: {}", ts(), if on { "Saving originals and applying" } else { "Restoring" }, t.name));
        self.set_on(&t.c, &t.id, on);
        self.status.insert(key.clone(), ("...", Instant::now()));
        self.busy.insert(key);
        let (cat, id, name) = (t.c.clone(), t.id.clone(), t.name.clone());
        self.work(move |tx| {
            let res = run_ops(&tx, &name, on, ops, backup);
            tx.send(Msg::OpsDone { cat, id, on, res, record });
        });
    }

    /// `items`: script tweaks ("category|id", check command); `ops_items`: engine tweaks for a probe.
    fn check_state(&mut self, items: Vec<(String, Option<String>)>, ops_items: Vec<Value>) {
        if self.checking {
            return;
        }
        self.checking = true;
        self.check_keys = items.iter().map(|i| i.0.clone()).chain(ops_items.iter().filter_map(|o| o["key"].as_str().map(String::from))).collect();
        let total = self.check_keys.len();
        self.log.push(format!("{} Checking system state for {} tweaks...", ts(), total));
        self.work(move |tx| {
            if !ops_items.is_empty() {
                match engine::run("probe", json!({ "items": ops_items }), 300) {
                    Ok(r) => {
                        let map = r["states"].as_object().map(|m| m.iter().map(|(k, v)| (k.clone(), v.as_str().unwrap_or("error").to_string())).collect()).unwrap_or_default();
                        tx.send(Msg::Probe(map));
                    }
                    Err(e) => tx.log(format!("{} State read failed: {e}", ts())),
                }
            }
            let chunks: Vec<_> = items.chunks(CHECK_BATCH).map(|c| c.to_vec()).collect();
            let n = chunks.len();
            for (i, chunk) in chunks.into_iter().enumerate() {
                let with: Vec<(String, String)> = chunk.iter().filter_map(|(id, c)| c.clone().map(|c| (id.clone(), c))).collect();
                let mut map = sys::check_batch(&with);
                for (id, _) in &chunk {
                    map.entry(id.clone()).or_insert(false);
                }
                tx.log(format!("{} Detected {}/{}...", ts(), ((i + 1) * CHECK_BATCH).min(total), total));
                tx.send(Msg::Checked { map, last: i + 1 == n, total });
            }
            if n == 0 {
                tx.send(Msg::Checked { map: HashMap::new(), last: true, total });
            }
        });
    }

    fn startup_toggle(&mut self, id: String, name: String, enable: bool, record: bool) {
        let admin = self.admin;
        self.log.push(format!("{} Startup {}: {}", ts(), if enable { "enable" } else { "disable" }, name));
        self.work(move |tx| {
            let res = sys::startup_set(&id, enable, admin);
            tx.send(Msg::StartupDone { id, name, enable, res, record });
        });
    }

    fn push_history(&mut self, h: Hist) {
        self.saved.history.insert(0, h);
        self.saved.history.truncate(MAX_HISTORY);
    }

    fn handle(&mut self, m: Msg) {
        match m {
            Msg::Log(s) => self.log.push(s),
            Msg::TweakDone { cat, id, on, res, record } => {
                let key = format!("{cat}|{id}");
                self.busy.remove(&key);
                let name = self.tweaks.iter().find(|t| t.c == cat && t.id == id).map(|t| t.name.clone()).unwrap_or_default();
                match res {
                    Ok(()) => {
                        self.set_on(&cat, &id, on);
                        self.probe.insert(key.clone(), if on { "on" } else { "off" }.into());
                        self.status.insert(key, ("OK", Instant::now()));
                        self.log.push(format!("{} {}: {}", ts(), name, if on { "APPLIED" } else { "REVERTED" }));
                        if record {
                            let (t, d) = sys::local_time();
                            self.push_history(Hist { id, name, config: cat, applied: on, when: format!("{d} {t}") });
                        }
                    }
                    Err(e) => {
                        self.set_on(&cat, &id, !on);
                        let tag = if e.contains("ADMIN_REQUIRED") { "ADMIN" } else { "FAIL" };
                        self.status.insert(key, (tag, Instant::now()));
                        self.log.push(format!("{} {}: ERROR - {}", ts(), name, e));
                    }
                }
                self.save();
            }
            Msg::OpsDone { cat, id, on, res, record } => {
                let key = format!("{cat}|{id}");
                self.busy.remove(&key);
                let name = self.tweaks.iter().find(|t| t.c == cat && t.id == id).map(|t| t.name.clone()).unwrap_or_default();
                match res {
                    Ok(backup) => {
                        match backup {
                            Some(b) => {
                                self.saved.backups.insert(key.clone(), b);
                            }
                            None => {
                                self.saved.backups.remove(&key);
                            }
                        }
                        self.set_on(&cat, &id, on);
                        self.probe.insert(key.clone(), if on { "on" } else { "off" }.into());
                        self.status.insert(key, ("OK", Instant::now()));
                        self.log.push(format!("{} {}: {} and verified", ts(), name, if on { "APPLIED" } else { "RESTORED" }));
                        if record {
                            let (t, d) = sys::local_time();
                            self.push_history(Hist { id, name, config: cat, applied: on, when: format!("{d} {t}") });
                        }
                    }
                    Err(e) => {
                        self.set_on(&cat, &id, !on);
                        let tag = if e.contains("ADMIN_REQUIRED") || e.starts_with("ACCESS DENIED") {
                            "ADMIN"
                        } else if e.starts_with("NOT_SUPPORTED") {
                            self.probe.insert(key.clone(), "na".into());
                            "N/A"
                        } else {
                            "FAIL"
                        };
                        self.status.insert(key, (tag, Instant::now()));
                        self.log.push(format!("{} {}: ERROR - {}", ts(), name, e));
                    }
                }
                self.save();
            }
            Msg::Probe(map) => {
                for (key, st) in map {
                    if let Some((cat, id)) = key.split_once('|') {
                        if st == "on" || st == "off" {
                            self.set_on(cat, id, st == "on");
                        }
                    }
                    self.probe.insert(key, st);
                }
                self.save();
            }
            Msg::Checked { map, last, total } => {
                for (key, v) in map {
                    if let Some((cat, id)) = key.split_once('|') {
                        self.set_on(cat, id, v);
                    }
                    self.probe.insert(key, if v { "on" } else { "off" }.into());
                }
                if last {
                    self.checking = false;
                    let active = self.check_keys.iter().filter_map(|k| k.split_once('|')).filter(|(c, id)| self.is_on(c, id)).count();
                    self.log.push(format!("{} State check complete: {} tweaks checked, {} active", ts(), total, active));
                    self.toast("State read from Windows", format!("{active} of {total} tweaks are applied"));
                    self.save();
                }
            }
            Msg::Metrics(m) => self.metrics = Some((m, Instant::now())),
            Msg::Static(a, b, c) => self.os = (a, b, c),
            Msg::Procs(v, n) => {
                self.procs = v;
                self.proc_total = n;
            }
            Msg::Startup(r) => self.startup = Some(r),
            Msg::StartupDone { id, name, enable, res, record } => match res {
                Ok(()) => {
                    self.log.push(format!("{} Verified: \"{}\" is now {} (read-back check passed).", ts(), name, if enable { "ENABLED" } else { "DISABLED" }));
                    if let Some(Ok(items)) = &mut self.startup {
                        if let Some(it) = items.iter_mut().find(|i| i.id == id) {
                            it.enabled = enable;
                        }
                    }
                    if record {
                        let (t, d) = sys::local_time();
                        self.push_history(Hist { id, name, config: "startup".into(), applied: !enable, when: format!("{d} {t}") });
                        self.save();
                    }
                }
                Err(e) => self.log.push(format!("{} ERROR: {}", ts(), e)),
            },
            Msg::Plans(v) => self.plans = Some(v),
            Msg::CleanDone(id, ok) => {
                let name = CLEANERS.iter().find(|c| c.0 == id).map_or("", |c| c.1);
                if ok {
                    self.toast("Cleaning done", format!("{name} is clean."));
                } else {
                    self.toast("Cleaning failed", format!("{name} couldn't be cleaned. Some parts need administrator rights."));
                }
                self.clean.insert(id, (if ok { "CLEANED" } else { "FAILED" }, Instant::now()));
            }
            Msg::Toast(a, b) => self.toast(a, b),
            Msg::Games(g) => self.games = Some(g),
            Msg::Picked(Ok(Some(a))) => {
                self.arts.remove(&a.id);
                self.saved.arena_last = a.id.clone();
                self.saved.arena_apps.retain(|x| x.id != a.id);
                self.toast("Added to Arena", format!("{} is in your library. Tune it, then launch it from here.", a.name));
                self.saved.arena_apps.push(a);
                self.save();
            }
            Msg::Picked(Ok(None)) => {}
            Msg::Picked(Err(e)) => self.toast("Couldn't add the program", e),
            Msg::Update(r) => {
                self.update = Some((r, None));
                self.notif_open = true;
            }
            Msg::UpdateFailed(e) => {
                if let Some(u) = &mut self.update {
                    u.1 = Some(Some(e));
                }
            }
            Msg::HistoryCleared => {
                self.reverting = false;
                self.saved.history.clear();
                self.save();
                self.toast("History reverted", "Every entry was undone, newest first");
            }
        }
    }

