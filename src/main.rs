/// Design tokens: one radius per kind of element, used everywhere.
const R_CARD: f32 = 8.0;
const R_CTRL: f32 = 6.0;
const R_TAG: f32 = 4.0;

fn ease(t: f32) -> f32 {
    let t = t.clamp(0.0, 1.0);
    t * t * (3.0 - 2.0 * t)
}

fn mix(a: Color32, b: Color32, t: f32) -> Color32 {
    a.lerp_to_gamma(b, t)
}

/// Part of a ring, starting at 12 o'clock.
fn arc(painter: &egui::Painter, col: Color32, c: Pos2, rad: f32, frac: f32, width: f32) {
    if frac < 0.004 {
        return;
    }
    let n = (72.0 * frac).ceil().max(2.0) as usize;
    let pts: Vec<Pos2> = (0..=n)
        .map(|i| {
            let a = std::f32::consts::TAU * frac * (i as f32 / n as f32) - std::f32::consts::FRAC_PI_2;
            c + rad * vec2(a.cos(), a.sin())
        })
        .collect();
    for end in [pts[0], pts[n]] {
        painter.circle_filled(end, width / 2.0, col);
    }
    painter.add(PathShape::line(pts, PathStroke::new(width, col)));
}

