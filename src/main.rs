#[derive(Clone, Copy, PartialEq)]
enum Kind {
    Ghost,
    Primary,
    Danger,
}

/// A button. Hover lifts the fill, press darkens it; the label never moves.
fn btn_ex(ui: &mut egui::Ui, p: &Pal, glyph: Option<&str>, s: &str, kind: Kind) -> egui::Response {
    let galley = ui.painter().layout_no_wrap(s.to_owned(), semi(12.0), Color32::PLACEHOLDER);
    let iw = if glyph.is_some() { 20.0 } else { 0.0 };
    let (r, resp) = ui.allocate_exact_size(vec2((galley.size().x + iw + 26.0).max(64.0), 30.0), Sense::click());
    let h = ui.ctx().animate_bool_with_time(resp.id, resp.hovered(), 0.10);
    let down = resp.is_pointer_button_down_on();
    let painter = ui.painter();
    let fg = match kind {
        Kind::Primary => {
            let fill = if down { mix(p.acc, p.bg, 0.15) } else { mix(p.acc, p.acc_hi, h) };
            painter.rect_filled(r, R_CTRL, fill);
            p.on_acc
        }
        Kind::Ghost => {
            let fill = if down { p.border } else { alpha(p.hover, h) };
            painter.rect(r, R_CTRL, fill, Stroke::new(1.0_f32, mix(p.border, p.border_hi, h)), StrokeKind::Inside);
            p.text
        }
        Kind::Danger => {
            painter.rect(r, R_CTRL, alpha(p.fail, if down { 0.18 } else { 0.10 * h }), Stroke::new(1.0_f32, alpha(p.fail, 0.35 + 0.3 * h)), StrokeKind::Inside);
            p.fail
        }
    };
    if resp.has_focus() {
        painter.rect_stroke(r.expand(2.0), R_CTRL + 2.0, Stroke::new(1.5_f32, alpha(p.acc, 0.6)), StrokeKind::Outside);
    }
    let x = r.center().x - (galley.size().x + iw) / 2.0;
    if let Some(g) = glyph {
        painter.text(pos2(x + 7.0, r.center().y), Align2::CENTER_CENTER, g, icon_font(12.0), fg);
    }
    painter.galley(pos2(x + iw, r.center().y - galley.size().y / 2.0), galley, fg);
    resp.on_hover_cursor(egui::CursorIcon::PointingHand)
}

fn btn(ui: &mut egui::Ui, p: &Pal, s: &str) -> egui::Response {
    btn_ex(ui, p, None, s, Kind::Ghost)
}

/// A small badge (not clickable): an optional icon and a label.
fn pill(ui: &mut egui::Ui, glyph: Option<&str>, s: &str, col: Color32, fill: Color32, edge: Color32) {
    let galley = ui.painter().layout_no_wrap(s.to_owned(), semi(11.0), col);
    let iw = if glyph.is_some() { 16.0 } else { 0.0 };
    let (r, _) = ui.allocate_exact_size(vec2(galley.size().x + iw + 14.0, 20.0), Sense::hover());
    ui.painter().rect(r, R_TAG, fill, Stroke::new(1.0_f32, edge), StrokeKind::Inside);
    if let Some(g) = glyph {
        ui.painter().text(pos2(r.left() + 13.0, r.center().y), Align2::CENTER_CENTER, g, icon_font(10.0), col);
    }
    ui.painter().galley(pos2(r.left() + 7.0 + iw, r.center().y - galley.size().y / 2.0), galley, col);
}

fn tag(ui: &mut egui::Ui, s: &str, col: Color32) {
    pill(ui, None, s, col, alpha(col, 0.10), Color32::TRANSPARENT);
}

/// The ON/OFF switch. ON = the tweak is applied.
fn toggle(ui: &mut egui::Ui, p: &Pal, on: bool, busy: bool) -> egui::Response {
    let (rect, resp) = ui.allocate_exact_size(vec2(38.0, 22.0), if busy { Sense::hover() } else { Sense::click() });
    let t = ease(ui.ctx().animate_bool_with_time(resp.id, on, 0.16));
    let h = ui.ctx().animate_bool_with_time(resp.id.with("hover"), resp.hovered(), 0.10);
    // while its change runs the track pulses gently
    let fade = if busy {
        ui.ctx().request_repaint();
        0.55 + 0.25 * (ui.input(|i| i.time) * 5.0).sin() as f32
    } else {
        1.0
    };
    let painter = ui.painter();
    let off = mix(p.toggle, p.muted, 0.35 * h);
    let onc = mix(p.acc, p.acc_hi, h);
    painter.rect_filled(rect, rect.height() / 2.0, alpha(mix(off, onc, t), fade));
    let c = pos2(egui::lerp(rect.left() + 11.0..=rect.right() - 11.0, t), rect.center().y);
    let knob = Color32::WHITE;
    painter.circle_filled(c, if resp.is_pointer_button_down_on() { 8.0 } else { 7.5 }, knob);
    if !p.dark && t < 0.5 {
        painter.circle_stroke(c, 7.5, Stroke::new(1.0_f32, alpha(Color32::BLACK, 0.08)));
    }
    if resp.has_focus() {
        painter.rect_stroke(rect.expand(2.0), rect.height() / 2.0 + 2.0, Stroke::new(1.5_f32, alpha(p.acc, 0.6)), StrokeKind::Outside);
    }
    resp.on_hover_cursor(if busy { egui::CursorIcon::Wait } else { egui::CursorIcon::PointingHand })
}

#[derive(Clone, Copy)]
enum Chip<'a> {
    /// a glyph tile; the number (0..1) is how lit it is (lit = applied / active)
    Glyph(&'a str, f32),
    /// a glyph on an app's brand colour
    Brand(&'a str, u32),
    /// like `Brand`, with Brave's logo as a badge
    Brave(&'a str),
    /// a picture (an app's own icon); dimmed until lit
    Image(egui::TextureId, f32),
}

fn paint_chip(painter: &egui::Painter, p: &Pal, r: Rect, chip: Chip) {
    let rad = (r.width() * 0.22).min(R_CARD);
    let font = icon_font(r.width() * 0.44);
    match chip {
        Chip::Glyph(g, lit) => {
            painter.rect_filled(r, rad, mix(p.chip, p.acc_soft, lit));
            painter.text(r.center(), Align2::CENTER_CENTER, g, font, mix(p.dim, p.acc, lit));
        }
        Chip::Brand(g, col) => {
            painter.rect_filled(r, rad, hex(col));
            painter.text(r.center(), Align2::CENTER_CENTER, g, font, Color32::WHITE);
        }
        Chip::Brave(g) => {
            painter.rect_filled(r, rad, hex(icons::BRAVE_ORANGE));
            painter.text(r.center(), Align2::CENTER_CENTER, g, font, Color32::WHITE);
            let badge = Rect::from_center_size(r.right_bottom() - vec2(3.0, 3.0), Vec2::splat(r.width() * 0.46));
            painter.circle_filled(badge.center(), badge.width() / 2.0 + 2.0, Color32::WHITE);
            painter.image(p.brave, badge, UV, Color32::WHITE);
        }
        Chip::Image(tex, lit) => {
            painter.rect_filled(r, rad, mix(p.chip, p.acc_soft, lit));
            painter.image(tex, r.shrink(r.width() * 0.16), UV, mix(Color32::from_white_alpha(110), Color32::WHITE, lit));
        }
    }
}

const UV: Rect = Rect { min: pos2(0.0, 0.0), max: pos2(1.0, 1.0) };

/// Chip for a tweak: the app it targets if there is one, else its own glyph.
fn tweak_chip(t: &Tweak, lit: f32) -> Chip<'static> {
    let glyph = icons::tweak(&t.c, &t.id);
    match icons::brand(&t.c, &t.id) {
        Some((_, g, col)) => Chip::Brand(g, col),
        None if t.c == "brave" => Chip::Brave(glyph),
        None if t.c == "edge" => Chip::Brand("\u{E774}", 0x0c8a6e),
        None => Chip::Glyph(glyph, lit),
    }
}

