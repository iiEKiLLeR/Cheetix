impl eframe::App for App {
    fn update(&mut self, ctx: &egui::Context, _frame: &mut eframe::Frame) {
        while let Ok(m) = self.rx.try_recv() {
            self.handle(m);
        }
        let want = theme::index(&self.saved.theme);
        if !self.styled || want != self.theme {
            self.theme = want;
            self.p = theme::pal(want, &self.tex);
            self.styled = true;
            apply_style(ctx, &self.p);
        }
        let p = self.p;
        if ctx.input_mut(|i| i.consume_key(egui::Modifiers::CTRL, egui::Key::K)) {
            ctx.memory_mut(|m| m.request_focus(self.search_id));
        }
        if self.view == "dashboard" && self.last_poll.is_none_or(|t| t.elapsed() >= DASH_POLL) {
            self.poll_metrics();
        }

        let now = self.started.elapsed().as_secs_f32();
        theme::paint_ground(&ctx.layer_painter(egui::LayerId::background()), ctx.screen_rect(), &p, now, ctx.screen_rect().width() / 1280.0);
        if p.aura.is_some() {
            // the aurora drifts slowly; ~25 fps is smooth enough
            ctx.request_repaint_after(Duration::from_millis(40));
        }
        let chrome = |m: Margin| Frame::new().fill(p.side).inner_margin(m);
        egui::TopBottomPanel::top("top").exact_height(52.0).frame(chrome(Margin { left: 14, right: 6, top: 0, bottom: 0 })).show_separator_line(false).show(ctx, |ui| {
            self.top_bar(ui);
            let r = ui.max_rect();
            ui.painter().hline(r.x_range(), r.bottom() - 0.5, Stroke::new(1.0_f32, p.border));
        });
        egui::TopBottomPanel::bottom("bottom").exact_height(28.0).frame(chrome(Margin::symmetric(14, 0))).show_separator_line(false).show(ctx, |ui| {
            let r = ui.max_rect();
            ui.painter().hline(r.x_range(), r.top() + 0.5, Stroke::new(1.0_f32, p.border));
            self.bottom_bar(ui);
        });
        egui::SidePanel::left("nav").exact_width(232.0).resizable(false).frame(chrome(Margin { left: 8, right: 8, top: 0, bottom: 4 })).show_separator_line(false).show(ctx, |ui| {
            let r = ui.max_rect();
            self.sidebar(ui);
            ui.painter().vline(r.right() + 7.5, r.y_range(), Stroke::new(1.0_f32, p.border));
        });
        egui::CentralPanel::default().frame(Frame::new()).show(ctx, |ui| {
            egui::ScrollArea::vertical().id_salt(self.view).auto_shrink([false, false]).show(ui, |ui| {
                Frame::new().inner_margin(Margin { left: 28, right: 28, top: 22, bottom: 24 }).show(ui, |ui| {
                    ui.set_width(ui.available_width());
                    ui.spacing_mut().item_spacing.y = 8.0;
                    // a page fades in when it is opened (short, no movement)
                    let t = ease(self.view_at.elapsed().as_secs_f32() / 0.15);
                    if t < 1.0 {
                        ui.set_opacity(t);
                        ctx.request_repaint();
                    }
                    match self.view {
                        "dashboard" => self.dashboard(ui),
                        "monitor" => self.monitor(ui),
                        "arena" => self.arena(ui),
                        "shortcuts" => self.shortcuts(ui),
                        "cleaner" => self.cleaner(ui),
                        "powerplans" => self.power_plans(ui),
                        "startup" => self.startup_page(ui),
                        "history" => self.history(ui),
                        "settings" => self.settings(ui),
                        "apps" => self.tweak_page(ui, "apps", "Windows Apps"),
                        v => {
                            if let Some((id, title, _)) = PAGES.iter().find(|x| x.0 == v) {
                                self.tweak_page(ui, id, title);
                            }
                        }
                    }
                });
            });
        });

        if let Some((a, b, at)) = &self.toast {
            let age = at.elapsed().as_secs_f32();
            if age < 3.2 {
                let t = ease(age / 0.18) * ease((3.2 - age) / 0.3);
                let (a, b) = (a.clone(), b.clone());
                egui::Area::new(egui::Id::new("toast")).order(egui::Order::Tooltip).anchor(Align2::RIGHT_BOTTOM, vec2(-20.0, -44.0)).show(ctx, |ui| {
                    ui.set_opacity(t);
                    let shadow = Shadow { offset: [0, 4], blur: 14, spread: 0, color: alpha(Color32::BLACK, if p.dark { 0.30 } else { 0.10 }) };
                    Frame::new().fill(p.solid).stroke(Stroke::new(1.0_f32, p.border)).corner_radius(R_CARD).shadow(shadow).inner_margin(Margin { left: 14, right: 16, top: 10, bottom: 10 }).show(ui, |ui| {
                        ui.set_max_width(380.0);
                        ui.set_min_width(240.0);
                        ui.horizontal(|ui| {
                            icon(ui, icons::CHECK, 12.0, p.acc);
                            ui.vertical(|ui| {
                                ui.spacing_mut().item_spacing.y = 2.0;
                                ui.label(RichText::new(a).font(semi(12.5)).color(p.text));
                                ui.add(egui::Label::new(RichText::new(b).size(12.0).color(p.dim)).wrap());
                            });
                        });
                    });
                });
                ctx.request_repaint();
            } else {
                self.toast = None;
            }
        }

        self.update_popup(ctx);
        // follow the Arena session (it runs as its own process)
        if self.session_read.elapsed() >= Duration::from_secs(1) {
            self.session_read = Instant::now();
            self.session = arena::status();
            if let Some(st) = &self.session {
                if st.running() && !arena::alive(st.pid) {
                    arena::recover_if_needed();
                }
                if self.close_when_live && st.phase == "active" {
                    ctx.send_viewport_cmd(ViewportCommand::Close);
                }
            }
        }

        // keep timers (status labels, session clock, monitor refresh) moving
        ctx.request_repaint_after(Duration::from_millis(500));

        // screenshots also wait for the page's state read, so cards show real states
        let read = self.page_tweaks(self.view).iter().all(|t| self.probe.contains_key(&format!("{}|{}", t.c, t.id)));
        let loaded = self.metrics.is_some() && !self.os.1.is_empty() && read;
        if let Some((path, frames, born, sent)) = &mut self.shot {
            *frames += 1;
            ctx.request_repaint();
            // ~120 frames, but give the system info (a slow PowerShell query) up to 15 s to arrive
            if !*sent && *frames >= 120 && (loaded || born.elapsed() > Duration::from_secs(15)) {
                *sent = true;
                ctx.send_viewport_cmd(ViewportCommand::Screenshot(Default::default()));
            }
            let img = ctx.input(|i| i.events.iter().find_map(|e| if let egui::Event::Screenshot { image, .. } = e { Some(image.clone()) } else { None }));
            if let Some(img) = img {
                if let Err(e) = save_png(path, &img) {
                    eprintln!("screenshot failed: {e}");
                    std::process::exit(1);
                }
                std::process::exit(0);
            }
            if born.elapsed() > Duration::from_secs(40) {
                eprintln!("screenshot never arrived");
                std::process::exit(1);
            }
        }
    }
}

fn save_png(path: &std::path::Path, img: &egui::ColorImage) -> Result<(), Box<dyn std::error::Error>> {
    if let Some(d) = path.parent().filter(|d| !d.as_os_str().is_empty()) {
        std::fs::create_dir_all(d)?;
    }
    let mut enc = png::Encoder::new(std::io::BufWriter::new(std::fs::File::create(path)?), img.size[0] as u32, img.size[1] as u32);
    enc.set_color(png::ColorType::Rgba);
    enc.set_depth(png::BitDepth::Eight);
    enc.write_header()?.write_image_data(img.as_raw())?;
    Ok(())
}

/// Started from a terminal: print there (eprintln, panics). Started from Explorer there is no
/// parent console, nothing is attached and no window appears. Panics also go to crash.log.
fn attach_console() {
    #[cfg(windows)]
    unsafe {
        windows_sys::Win32::System::Console::AttachConsole(windows_sys::Win32::System::Console::ATTACH_PARENT_PROCESS);
    }
    let prev = std::panic::take_hook();
    std::panic::set_hook(Box::new(move |info| {
        let log = state_path().with_file_name("crash.log");
        let _ = std::fs::create_dir_all(log.parent().unwrap_or(std::path::Path::new(".")));
        let (t, d) = sys::local_time();
        let _ = std::fs::OpenOptions::new().create(true).append(true).open(&log).and_then(|mut f| {
            use std::io::Write;
            writeln!(f, "[{d} {t}] {info}\n{}", std::backtrace::Backtrace::force_capture())
        });
        prev(info);
    }));
}

/// The taskbar / Alt+Tab icon (the exe's file icon is embedded by build.rs).
fn window_icon() -> egui::IconData {
    let mut r = png::Decoder::new(&include_bytes!("../assets/cheetix-256.png")[..]).read_info().expect("cheetix-256.png");
    let mut buf = vec![0; r.output_buffer_size()];
    let info = r.next_frame(&mut buf).expect("cheetix-256.png");
    buf.truncate(info.buffer_size());
    egui::IconData { rgba: buf, width: info.width, height: info.height }
}

fn main() -> eframe::Result {
    attach_console();
    let args: Vec<String> = std::env::args().collect();
    let arg = |name: &str| args.iter().position(|a| a == name).and_then(|i| args.get(i + 1)).cloned();
    let shot = arg("--screenshot").map(PathBuf::from);
    // --view and --theme open the app on a given page / in a given theme
    let (view, theme) = (arg("--view"), arg("--theme"));
    let mut vp = egui::ViewportBuilder::default()
        .with_title("Cheetix")
        .with_icon(window_icon())
        .with_inner_size([1280.0, 800.0])
        .with_min_inner_size([960.0, 600.0])
        .with_decorations(false);
    if shot.is_some() {
        vp = vp.with_active(false);
        #[cfg(windows)]
        {
            vp = vp.with_window_level(egui::WindowLevel::AlwaysOnBottom);
        }
    }
    let opts = eframe::NativeOptions { viewport: vp, ..Default::default() };
    eframe::run_native("Cheetix", opts, Box::new(move |cc| Ok(Box::new(App::new(cc, shot, view, theme)))))
}

