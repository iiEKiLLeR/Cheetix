/// The details panel under a tweak: what, why, gains, drawbacks, exact changes and how OFF undoes it.
fn details(ui: &mut egui::Ui, p: &Pal, c: &Card) {
    let t = c.t;
    let info = t.info.as_ref();
    let risk_col = |r: &str| match r {
        "high" => p.fail,
        "medium" => p.run,
        _ => p.ok,
    };
    ui.scope(|ui| {
        ui.spacing_mut().item_spacing.y = 3.0;
        let section = |ui: &mut egui::Ui, k: &str, v: &str, col: Color32| {
            overline(ui, p, k);
            ui.add(egui::Label::new(RichText::new(v).size(12.0).color(col)).wrap());
            ui.add_space(8.0);
        };
        section(ui, "What it does", &t.desc, p.text);
        section(ui, "Turning it ON", &format!("{}.", t.lab.on), p.text);
        section(ui, "Turning it OFF", &format!("{}.", c.off_text()), p.text);
        if let Some(info) = info {
            section(ui, "Why use it", &info.why, p.dim);
            section(ui, "Benefits", &info.gain, p.dim);
            section(ui, "Drawbacks", &info.cost, if info.risk == "low" { p.dim } else { risk_col(&info.risk) });
            section(ui, "Recommended for", &info.who, p.dim);
            ui.horizontal(|ui| {
                let rc = risk_col(&info.risk);
                pill(ui, Some(icons::WARN), &format!("Risk: {}", info.risk), rc, alpha(rc, 0.10), Color32::TRANSPARENT);
                pill(ui, Some(icons::REFRESH), if info.restart == "reboot" { "Restart needed" } else if info.restart == "none" { "Instant" } else { "Sign-out or app restart" }, p.dim, p.chip, Color32::TRANSPARENT);
                if t.ops.as_ref().is_some_and(|o| engine::needs_admin(o)) {
                    pill(ui, Some(icons::ADMIN), "Needs admin", p.dim, p.chip, Color32::TRANSPARENT);
                }
            });
            ui.add_space(8.0);
            section(ui, "Restart", restart_text(&info.restart), p.dim);
            if let Some(n) = &info.note {
                section(ui, "Note", n, p.run);
            }
        }
    });
}

/// Lays items out in one or two columns, depending on the room there is.
fn grid<T>(ui: &mut egui::Ui, items: &[T], mut each: impl FnMut(&mut egui::Ui, &T)) {
    let n = if ui.available_width() > 900.0 { 2 } else { 1 };
    ui.scope(|ui| {
        ui.spacing_mut().item_spacing = vec2(12.0, 10.0);
        ui.columns(n, |cols| {
            for (i, it) in items.iter().enumerate() {
                each(&mut cols[i % n], it);
            }
        });
    });
}

/// A clickable tile: icon and one line of text.
