fn state_path() -> PathBuf {
    let base = std::env::var("APPDATA").map(PathBuf::from).unwrap_or_else(|_| std::env::temp_dir());
    base.join("Cheetix").join("state.json")
}

/// The app was called TweakBox before: its saved states and saved originals move over once
/// (copied, so the old folder stays as a fallback).
fn migrate_state() {
    let new = state_path();
    // earlier names of the app, newest first
    let old = new.parent().and_then(|d| d.parent()).and_then(|b| ["SM7", "TweakBox"].iter().map(|n| b.join(n).join("state.json")).find(|o| o.exists()));
    if let (false, Some(old)) = (new.exists(), old) {
        if let Some(d) = new.parent() {
            let _ = std::fs::create_dir_all(d);
        }
        let _ = std::fs::copy(old, &new);
    }
}

// ---------------- messages from workers ----------------

enum Msg {
    Log(String),
    TweakDone { cat: String, id: String, on: bool, res: Result<(), String>, record: bool },
    /// an engine tweak finished: Ok(Some(backup)) after applying, Ok(None) after restoring
    OpsDone { cat: String, id: String, on: bool, res: Result<Option<Value>, String>, record: bool },
    /// read-only engine probe: "category|id" -> on / off / partial / na / error
    Probe(HashMap<String, String>),
    /// results of a state check, keyed "category|id"
    Checked { map: HashMap<String, bool>, last: bool, total: usize },
    Metrics(sys::Metrics),
    Static(String, String, String),
    Procs(Vec<sys::Proc>, usize),
    Startup(Result<Vec<sys::StartupItem>, String>),
    StartupDone { id: String, name: String, enable: bool, res: Result<(), String>, record: bool },
    Plans(Vec<sys::Plan>),
    CleanDone(String, bool),
    Toast(String, String),
    /// installed Steam games (Arena)
    Games(Result<Vec<arena::Game>, String>),
    /// a program picked with "Add a program" (None: cancelled)
    Picked(Result<Option<arena::App>, String>),
    /// a newer release is on GitHub
    Update(update::Release),
    /// the update could not be downloaded or started
    UpdateFailed(String),
    HistoryCleared,
}

#[derive(Clone)]
struct Tx(Sender<Msg>, egui::Context);
impl Tx {
    fn send(&self, m: Msg) {
        let _ = self.0.send(m);
        self.1.request_repaint();
    }
    fn log(&self, s: impl Into<String>) {
        self.send(Msg::Log(s.into()));
    }
}

fn ts() -> String {
    format!("[{}]", sys::local_time().0)
}

fn fmt_bytes(b: u64) -> String {
    let g = b as f64 / 1024f64.powi(3);
    if g >= 1.0 { format!("{g:.1} GB") } else { format!("{:.0} MB", b as f64 / 1024f64.powi(2)) }
}

fn fmt_uptime(s: u64) -> String {
    format!("{:02}:{:02}:{:02}", s / 3600, (s / 60) % 60, s % 60)
}

