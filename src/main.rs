#[derive(Deserialize, Clone)]
struct Tweak {
    c: String,
    id: String,
    name: String,
    desc: String,
    on: Option<String>,
    off: Option<String>,
    check: Option<String>,
    cmd: Option<String>,
    /// tweaks from data/ops.json: what to change, applied by the backup/restore engine
    ops: Option<Vec<serde_json::Value>>,
    info: Option<Info>,
    /// [min, max] Windows build this tweak applies to
    builds: Option<[u32; 2]>,
    /// "nvidia" / "amd": GPU vendor this tweak is for
    needs: Option<String>,
    /// what ON / OFF mean for this tweak (data/labels.json)
    #[serde(skip)]
    lab: Label,
    /// every setting this tweak changes, as comparable keys (two tweaks sharing one conflict)
    #[serde(skip)]
    targets: Vec<String>,
}

/// data/labels.json: generated by tools/gen_labels.py
#[derive(Deserialize, Clone, Default)]
struct Label {
    name: String,
    /// what ON does
    on: String,
    /// the Windows setting while the tweak is applied
    state: String,
    /// what OFF puts back
    subj: String,
    /// script tweaks only: what their fixed undo command does
    off: Option<String>,
    desc: Option<String>,
    /// risk of tweaks without a details block ("medium" / "high")
    risk: Option<String>,
}

#[derive(Deserialize, Clone)]
struct Info {
    why: String,
    gain: String,
    cost: String,
    who: String,
    restart: String,
    risk: String,
    note: Option<String>,
}

