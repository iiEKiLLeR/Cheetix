    fn history(&mut self, ui: &mut egui::Ui) {
        let p = self.p;
        let sub = if self.saved.history.is_empty() {
            "Nothing has been changed yet. Every switch you flip is listed here."
        } else {
            "Revert undoes one change. Revert all undoes every entry, newest first."
        };
        header(ui, &p, icons::nav("history"), "History", Some(format!("{} entries", self.saved.history.len())), sub);
        if self.saved.history.is_empty() {
            return;
        }
        let mut revert_all = false;
        ui.horizontal(|ui| {
            revert_all = btn_ex(ui, &p, Some(icons::UNDO), if self.reverting { "Reverting…" } else { "Revert all" }, Kind::Primary).clicked() && !self.reverting;
            if btn_ex(ui, &p, Some(icons::TRASH), "Clear history", Kind::Ghost).clicked() {
                self.saved.history.clear();
                self.save();
            }
        });
        ui.add_space(12.0);
        let mut undo = None;
        for (i, h) in self.saved.history.iter().enumerate() {
            let action = if h.config == "startup" {
                if h.applied { "Disabled" } else { "Enabled" }
            } else if h.applied {
                "Turned on"
            } else {
                "Turned off"
            };
            let glyph = if h.config == "startup" { icons::POWER } else { icons::tweak(&h.config, &h.id) };
            row(ui, &p, false, Chip::Glyph(glyph, 0.0), &h.name, &format!("{}  ·  {}  ·  {}", if h.config == "startup" { "Startup" } else { page_title(&h.config) }, h.when, action), 110.0, |ui| {
                if btn_ex(ui, &p, Some(icons::UNDO), "Revert", Kind::Ghost).clicked() {
                    undo = Some(i);
                }
            });
        }
        if let Some(i) = undo {
            let h = self.saved.history[i].clone();
            if h.config == "startup" {
                self.startup_toggle(h.id, h.name, h.applied, false);
            } else {
                self.apply(&h.config, &h.id, !h.applied, false);
            }
            self.saved.history.remove(i);
            self.save();
        }
        if revert_all {
            self.reverting = true;
            let jobs: Vec<(Hist, Option<String>, Option<Vec<Value>>)> = self
                .saved
                .history
                .iter()
                .map(|h| {
                    let t = self.tweaks.iter().find(|t| t.c == h.config && t.id == h.id);
                    let script = t.and_then(|t| if h.applied { t.off.clone() } else { t.on.clone() });
                    (h.clone(), script, t.and_then(|t| t.ops.clone()))
                })
                .collect();
            let admin = self.admin;
            // newest first; a tweak can appear more than once, so track its backup as jobs run
            let mut backups = self.saved.backups.clone();
            self.work(move |tx| {
                for (h, script, ops) in jobs {
                    if h.config == "startup" {
                        let res = sys::startup_set(&h.id, h.applied, admin);
                        tx.send(Msg::StartupDone { id: h.id, name: h.name, enable: h.applied, res, record: false });
                    } else if let Some(ops) = ops {
                        let key = format!("{}|{}", h.config, h.id);
                        let res = if !admin && engine::needs_admin(&ops) { Err(sys::ADMIN_MSG.to_string()) } else { run_ops(&tx, &h.name, !h.applied, ops, backups.get(&key).cloned()) };
                        match &res {
                            Ok(Some(b)) => {
                                backups.insert(key, b.clone());
                            }
                            Ok(None) => {
                                backups.remove(&key);
                            }
                            Err(_) => {}
                        }
                        tx.send(Msg::OpsDone { cat: h.config, id: h.id, on: !h.applied, res, record: false });
                    } else if let Some(s) = script {
                        let res = sys::run_bat(&s, admin).map(|_| ());
                        tx.send(Msg::TweakDone { cat: h.config, id: h.id, on: !h.applied, res, record: false });
                    }
                }
                tx.send(Msg::HistoryCleared);
            });
        }
    }

